import { writeFileSync } from "fs";
import path from "path";
import { fileURLToPath } from "url";
import {
  listValueRangeDiffCases,
  toValueRangeCaseExportName,
} from "./value-range-diff-case-definitions.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const packageRoot = path.resolve(__dirname, "..");
const storiesOutDir = path.resolve(packageRoot, "src/stories/json-schema-diffs-suite");
const testsOutDir = path.resolve(packageRoot, "src/it/json-schema-diffs-suite");

/** @type {Array<{ suiteKey: string, title: string, metaKebab: string, storyFileName: string, testFileName: string, diffUtilsModule: string, includeOas31Only: boolean, sampleBuilderModule: string, sampleBuilderName: string }>} */
const VALUE_RANGE_STORY_SUITES = [
  {
    suiteKey: "number-validation-value-range",
    title: "JSON Schema Diffs Suite/Number Validation Value Range Samples",
    metaKebab: "json-schema-diffs-suite-number-validation-value-range-samples",
    storyFileName: "number-validation-value-range.stories.tsx",
    testFileName: "number-validation-value-range.it-test.ts",
    diffUtilsModule: "./json-schema-diffs-utils",
    includeOas31Only: false,
    sampleBuilderModule: "./value-range-diff-samples",
    sampleBuilderName: "buildValueRangeDiffProgrammaticSampleCases",
  },
  {
    suiteKey: "number-validation-value-range-oas-3-1",
    title: "JSON Schema Diffs Suite/Number Validation Value Range OAS 3.1 Samples",
    metaKebab: "json-schema-diffs-suite-number-validation-value-range-oas-3-1-samples",
    storyFileName: "number-validation-value-range-oas-3-1.stories.tsx",
    testFileName: "number-validation-value-range-oas-3-1.it-test.ts",
    diffUtilsModule: "./json-schema-diffs-oas-3-1-utils",
    includeOas31Only: true,
    sampleBuilderModule: "./value-range-diff-oas-31-samples",
    sampleBuilderName: "buildValueRangeDiffOas31ProgrammaticSampleCases",
  },
];

/**
 * @param {typeof VALUE_RANGE_STORY_SUITES[number]} suite
 * @param {ReturnType<typeof listValueRangeDiffCases>} cases
 */
const printStoryFile = (suite, cases) => {
  const exports = cases
    .map(
      (sampleCase) =>
        `export const ${toValueRangeCaseExportName(sampleCase.caseId)}: Story = createCaseStory("${sampleCase.caseId}");`,
    )
    .join("\n");

  return `/**
 * Programmatic value-range diff stories (see src/stories/json-schema-diffs-suite/value-range-diff-case-definitions.ts).
 * Regenerate: node --experimental-strip-types bin/generate-value-range-diff-stories.mjs
 */
import type { Meta, StoryObj } from "@storybook/react";
import {
  JsonSchemaDiffSamplesStory,
  createJsonSchemaDiffCaseStoryFactory,
  createJsonSchemaDiffSampleById,
  jsonSchemaDiffSampleReadonlyArgTypes,
} from "${suite.diffUtilsModule}";
import { ${suite.sampleBuilderName} } from "${suite.sampleBuilderModule}";

const sampleCases = ${suite.sampleBuilderName}({ includeOas31Only: ${suite.includeOas31Only} });
const sampleById = createJsonSchemaDiffSampleById(sampleCases);

// eslint-disable-next-line storybook/story-exports
const meta = {
  title: "${suite.title}",
  component: JsonSchemaDiffSamplesStory,
  argTypes: jsonSchemaDiffSampleReadonlyArgTypes,
} satisfies Meta<typeof JsonSchemaDiffSamplesStory>;

export default meta;

type Story = StoryObj<typeof meta>;

const createCaseStory = createJsonSchemaDiffCaseStoryFactory(
  JsonSchemaDiffSamplesStory,
  sampleById,
);

${exports}
`;
};

/**
 * @param {typeof VALUE_RANGE_STORY_SUITES[number]} suite
 * @param {ReturnType<typeof listValueRangeDiffCases>} cases
 */
const printTestFile = (suite, cases) => {
  const tests = cases
    .map(
      (sampleCase) => `
  it("${sampleCase.caseId}", async () => {
    story = await storyPage(page, \`${suite.metaKebab}--case-${sampleCase.caseId}\`);
    await waitForJsonSchemaDiffViewer();
    component = await story.viewComponent();
    expect(await component.captureScreenshot()).toMatchImageSnapshot();
  });`,
    )
    .join("\n");

  return `/**
 * Generated by packages/api-doc-viewer/bin/generate-value-range-diff-stories.mjs
 * Edit together with src/stories/json-schema-diffs-suite/${suite.storyFileName}
 */
import { StoryPage } from "../service/story-page";
import { ViewComponent } from "../service/view-component";
import { storyPage } from "../service/storybook-service";

const META_ID = "${suite.metaKebab}";

async function waitForJsonSchemaDiffViewer() {
  await page.waitForSelector('[data-name="JsonNode"]', { visible: true });
  await page.waitForFunction(() => document.readyState === "complete");
  await page.evaluate(() => new Promise<void>((resolve) =>
    requestAnimationFrame(() => requestAnimationFrame(() => resolve())),
  ));
}

describe("${suite.title}", () => {
  let story: StoryPage;
  let component: ViewComponent;

  beforeEach(async () => {
    await jestPuppeteer.resetPage();
  });
${tests}
});
`;
};

for (const suite of VALUE_RANGE_STORY_SUITES) {
  const cases = listValueRangeDiffCases({ includeOas31Only: suite.includeOas31Only });
  const storyPath = path.join(storiesOutDir, suite.storyFileName);
  const testPath = path.join(testsOutDir, suite.testFileName);
  writeFileSync(storyPath, printStoryFile(suite, cases));
  writeFileSync(testPath, printTestFile(suite, cases));
  console.log(`Generated ${cases.length} programmatic cases -> ${suite.storyFileName}`);
}
